/**
 * Builds the phones' visual host: src/visual-host bundled with Mermaid and
 * DOMPurify into ONE self-contained HTML file, written to
 * apps/mobile/assets/visual-host/visual-host.html. The Expo app bundles it as
 * an asset and the Android app reads the same folder as its assets.
 *
 * The file is committed. tests/unit/visual-host-asset.test.ts fails when its
 * stamped input hash no longer matches the sources, so rerun this after a
 * change to any input: node scripts/build-visual-host.mjs
 *
 * No shebang: the test imports this file, and on a Windows checkout (CRLF) the
 * test runner's transform does not strip one, so the import fails to parse.
 */
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const VISUAL_HOST_OUT = join(root, 'apps/mobile/assets/visual-host/visual-host.html')
const INPUTS = [
  'src/visual-host/index.ts',
  'src/shared/chat-visuals.ts',
  'src/renderer/components/chat/visuals/diagram-render.ts',
  'scripts/build-visual-host.mjs',
]

/**
 * Hash of every input, including the bundled library versions. Line endings are
 * normalised so a Windows checkout (CRLF) hashes the same as the committed stamp.
 */
export function visualHostInputHash() {
  const hash = createHash('sha256')
  for (const file of INPUTS) hash.update(readFileSync(join(root, file), 'utf8').replaceAll('\r\n', '\n'))
  for (const pkg of ['mermaid', 'dompurify']) {
    hash.update(JSON.parse(readFileSync(join(root, 'node_modules', pkg, 'package.json'), 'utf8')).version)
  }
  return hash.digest('hex').slice(0, 16)
}

// The page may run its own inline script and nothing else: no network, no frames, no forms.
const CSP = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; font-src data:; base-uri 'none'; form-action 'none'"

async function build() {
  const { build: esbuild } = await import('esbuild')
  const result = await esbuild({
    entryPoints: [join(root, 'src/visual-host/index.ts')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    write: false,
    legalComments: 'none',
    logLevel: 'warning',
  })
  // A literal </script> inside the bundle would end the tag early.
  const js = result.outputFiles[0].text.replaceAll('</script', '<\\/script')
  const html = `<!doctype html><!-- visual-host ${visualHostInputHash()}: generated by scripts/build-visual-host.mjs, do not edit -->
<html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="${CSP}">
<meta name="viewport" content="width=device-width,initial-scale=1"><style>html,body{margin:0;padding:0;overflow:hidden}#root{padding:8px}#root svg{display:block;max-width:100%;height:auto;margin:0 auto}</style>
</head><body><div id="root"></div><script>${js}</script></body></html>
`
  mkdirSync(dirname(VISUAL_HOST_OUT), { recursive: true })
  writeFileSync(VISUAL_HOST_OUT, html)
  console.log(`wrote ${VISUAL_HOST_OUT} (${(Buffer.byteLength(html) / 1024).toFixed(0)} KiB)`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await build()
